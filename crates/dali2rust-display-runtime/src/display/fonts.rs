const ASCII_FIRST: u32 = 0x20;
const ASCII_LAST: u32 = 0x7E;

pub fn lookup_glyph_5x8(code: u32) -> Option<&'static [u8; 5]> {
    if (ASCII_FIRST..=ASCII_LAST).contains(&code) {
        let idx = (code - ASCII_FIRST) as usize * FONT_5X8_BYTES_PER_CHAR;
        Some(<&[u8; 5]>::try_from(&FONT_5X8_ASCII[idx..idx + 5]).unwrap())
    } else {
        FONT_5X8_CYRILLIC
            .binary_search_by_key(&code, |(c, _)| *c)
            .ok()
            .map(|i| &FONT_5X8_CYRILLIC[i].1)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookup_space() {
        let g = lookup_glyph_5x8(b' ' as u32).unwrap();
        assert_eq!(g, &[0, 0, 0, 0, 0]);
    }

    #[test]
    fn lookup_a() {
        let g = lookup_glyph_5x8(b'A' as u32).unwrap();
        assert_eq!(g, &[0x7E, 0x11, 0x11, 0x11, 0x7E]);
    }

    #[test]
    fn lookup_z() {
        let g = lookup_glyph_5x8(b'Z' as u32).unwrap();
        assert_eq!(g, &[0x61, 0x51, 0x49, 0x45, 0x43]);
    }

    #[test]
    fn lookup_digit() {
        let g = lookup_glyph_5x8(b'0' as u32).unwrap();
        assert_eq!(g, &[0x3E, 0x51, 0x49, 0x45, 0x3E]);
    }

    #[test]
    fn lookup_unknown() {
        assert_eq!(lookup_glyph_5x8(0x01), None);
    }

    #[test]
    fn lookup_cyrillic_a() {
        let g = lookup_glyph_5x8(0x0410).unwrap();
        assert_eq!(g, &[0x7E, 0x11, 0x11, 0x11, 0x7E]);
    }

    #[test]
    fn cyrillic_table_sorted() {
        for w in FONT_5X8_CYRILLIC.windows(2) {
            assert!(w[0].0 < w[1].0, "not sorted at code {}", w[0].0);
        }
    }
}
